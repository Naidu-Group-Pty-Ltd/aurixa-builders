const PREDICTOR_TRANSFORM = 0;
const COLOR_TRANSFORM = 1;
const SUBTRACT_GREEN = 2;
const COLOR_INDEXING_TRANSFORM = 3;

interface Transform {
  type: number;
  bits: number;
  width: number;
  height: number;
  data: Uint32Array;
}

const clamp255 = (value: number) => value < 0 ? 0 : value > 255 ? 255 : value;

/** Average of two packed ARGB values, per channel. */
function average2(a: number, b: number): number {
  return ((((a >>> 24) + (b >>> 24)) >> 1) << 24
    | ((((a >> 16) & 0xff) + ((b >> 16) & 0xff)) >> 1) << 16
    | ((((a >> 8) & 0xff) + ((b >> 8) & 0xff)) >> 1) << 8
    | (((a & 0xff) + (b & 0xff)) >> 1)) >>> 0;
}

/** The specification's gradient predictor, clamped per channel. */
function clampAddSubtractFull(left: number, top: number, topLeft: number): number {
  let out = 0;
  for (let shift = 0; shift < 32; shift += 8) {
    const value = ((left >> shift) & 0xff) + ((top >> shift) & 0xff)
      - ((topLeft >> shift) & 0xff);
    out |= clamp255(value) << shift;
  }
  return out >>> 0;
}

function select(top: number, left: number, topLeft: number): number {
  let predictLeft = 0;
  let predictTop = 0;
  for (let shift = 0; shift < 32; shift += 8) {
    const t = (top >> shift) & 0xff;
    const l = (left >> shift) & 0xff;
    const tl = (topLeft >> shift) & 0xff;
    predictLeft += Math.abs(tl - t);
    predictTop += Math.abs(tl - l);
  }
  return predictLeft < predictTop ? left : top;
}

function clampAddSubtractHalf(a: number, b: number): number {
  let out = 0;
  for (let shift = 0; shift < 32; shift += 8) {
    const av = (a >> shift) & 0xff;
    const bv = (b >> shift) & 0xff;
    // Truncating halving, not an arithmetic shift: the reference divides by
    // two in C, which rounds toward zero, and `>> 1` rounds toward minus
    // infinity. They differ on every negative odd difference.
    out |= clamp255(av + ((av - bv) / 2 | 0)) << shift;
  }
  return out >>> 0;
}

function predict(mode: number, left: number, top: number, topLeft: number,
  topRight: number): number {
  switch (mode) {
    case 0: return 0xff000000;
    case 1: return left;
    case 2: return top;
    case 3: return topRight;
    case 4: return topLeft;
    case 5: return average2(average2(left, topRight), top);
    case 6: return average2(left, topLeft);
    case 7: return average2(left, top);
    case 8: return average2(topLeft, top);
    case 9: return average2(top, topRight);
    case 10: return average2(average2(left, topLeft), average2(top, topRight));
    case 11: return select(top, left, topLeft);
    case 12: return clampAddSubtractFull(left, top, topLeft);
    case 13: return clampAddSubtractHalf(average2(left, top), topLeft);
    default: return 0xff000000;
  }
}

function applyPredictor(pixels: Uint32Array, width: number, height: number,
  transform: Transform): void {
  const bits = transform.bits;
  const tilesPerRow = (width + (1 << bits) - 1) >> bits;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const index = y * width + x;
      if (y === 0 && x === 0) {
        pixels[index] = (pixels[index] + 0xff000000) >>> 0;
        continue;
      }
      let predicted: number;
      if (y === 0) predicted = pixels[index - 1];
      else if (x === 0) predicted = pixels[index - width];
      else {
        const tile = transform.data[(y >> bits) * tilesPerRow + (x >> bits)];
        const mode = (tile >> 8) & 0xff;
        const left = pixels[index - 1];
        const top = pixels[index - width];
        const topLeft = pixels[index - width - 1];
        /*
         * NO SPECIAL CASE ON THE LAST COLUMN, deliberately. The reference
         * decoder reads its row buffer straight through, so "top-right" of the
         * rightmost pixel is the FIRST PIXEL OF THE CURRENT ROW — an artefact
         * of the layout that the format then depends on. Clamping to the pixel
         * above instead is a plausible-looking read that puts a handful of
         * pixels per picture wrong, which is not lossless.
         */
        const topRight = pixels[index - width + 1];
        predicted = predict(mode, left, top, topLeft, topRight);
      }
      const value = pixels[index];
      pixels[index] = (
        ((((value >>> 24) + (predicted >>> 24)) & 0xff) << 24)
        | (((((value >> 16) & 0xff) + ((predicted >> 16) & 0xff)) & 0xff) << 16)
        | (((((value >> 8) & 0xff) + ((predicted >> 8) & 0xff)) & 0xff) << 8)
        | (((value & 0xff) + (predicted & 0xff)) & 0xff)
      ) >>> 0;
    }
  }
}

const signed8 = (value: number) => (value << 24) >> 24;

function applyColourTransform(pixels: Uint32Array, width: number, height: number,
  transform: Transform): void {
  const bits = transform.bits;
  const tilesPerRow = (width + (1 << bits) - 1) >> bits;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const tile = transform.data[(y >> bits) * tilesPerRow + (x >> bits)];
      const greenToRed = signed8(tile & 0xff);
      const greenToBlue = signed8((tile >> 8) & 0xff);
      const redToBlue = signed8((tile >> 16) & 0xff);

      const index = y * width + x;
      const value = pixels[index];
      const green = (value >> 8) & 0xff;
      let red = (value >> 16) & 0xff;
      let blue = value & 0xff;
      red = (red + ((greenToRed * signed8(green)) >> 5)) & 0xff;
      blue = (blue + ((greenToBlue * signed8(green)) >> 5)
        + ((redToBlue * signed8(red)) >> 5)) & 0xff;
      pixels[index] = ((value & 0xff00ff00) | (red << 16) | blue) >>> 0;
    }
  }
}

function applySubtractGreen(pixels: Uint32Array): void {
  for (let i = 0; i < pixels.length; i++) {
    const value = pixels[i];
    const green = (value >> 8) & 0xff;
    pixels[i] = ((value & 0xff00ff00)
      | ((((value >> 16) & 0xff) + green) & 0xff) << 16
      | (((value & 0xff) + green) & 0xff)) >>> 0;
  }
}

/** Expand a palette-indexed row back to full width. */
function applyColourIndexing(pixels: Uint32Array, packedWidth: number, width: number,
  height: number, transform: Transform): PixelBuffer | null {
  const paletteSize = transform.width;
  const bitsPerPixel = paletteSize <= 2 ? 1 : paletteSize <= 4 ? 2 : paletteSize <= 16 ? 4 : 8;
  const perByte = 8 / bitsPerPixel;
  const out = new Uint32Array(width * height);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const packedIndex = y * packedWidth + ((x / perByte) | 0);
      if (packedIndex >= pixels.length) return null;
      const green = (pixels[packedIndex] >> 8) & 0xff;
      const shift = bitsPerPixel * (x % perByte);
      const entry = (green >> shift) & ((1 << bitsPerPixel) - 1);
      out[y * width + x] = entry < paletteSize ? transform.data[entry] : 0xff000000;
    }
  }
  return out;
}

