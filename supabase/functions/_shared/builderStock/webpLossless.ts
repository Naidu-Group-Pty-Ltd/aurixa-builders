/**
 * Builder stock — reading a lossless WebP (VP8L).
 *
 * WHY THIS IS HERE AT ALL. Display eligibility decides by DECODING the picture
 * and measuring what has been drawn on it, and it fails closed: a container no
 * decoder here reads is `pending`, which shows no image. Builder Stock accepts
 * WebP, so leaving it undecodable meant every future WebP upload — including a
 * perfectly clean builder photograph — had an empty card. Failing closed is
 * right; failing closed on a format the product accepts is a gap, not a policy.
 *
 * WHY IT IS WRITTEN RATHER THAN INSTALLED. This runs inside a Supabase edge
 * function. The vetted decoder for WebP is libwebp, which reaches JavaScript
 * only as a WebAssembly or asm.js build — a binary blob nobody reviewing this
 * repository can read, fetched at deploy time, for a module whose entire job is
 * to be a deterministic, bounded, auditable measurement. So the format is
 * implemented from its specification, in the same shape as the PNG, JPEG and
 * GIF readers beside it, and validated against libwebp's own output through
 * fixtures generated by it.
 *
 * WHAT IT IS ALLOWED TO COST. Everything here is bounded before it is
 * attempted: dimensions are checked against the caller's pixel ceiling before a
 * buffer is allocated, every Huffman read is length-limited, and a backward
 * reference that points outside the picture ends the decode rather than
 * wrapping. A malformed file returns null; it never throws and never loops.
 *
 * NOTHING HERE WRITES ANYTHING. The bytes handed in are read and not modified,
 * and the pixels produced exist only to be measured.
 */

/**
 * A pixel buffer this module allocated, named with its backing store.
 *
 * `Uint32Array` on its own means `Uint32Array<ArrayBufferLike>`, which admits a
 * `SharedArrayBuffer` — so a function returning one cannot be assigned to a
 * variable holding a buffer this module made, and the transforms below hand
 * exactly that back. Every buffer here is a fresh `new Uint32Array(n)`, so
 * saying so is both accurate and what makes the assignment type-check.
 *
 * Deliberately used on RETURNS and locals only. Parameters stay the wide
 * `Uint32Array`: narrowing what a function will accept would be the opposite
 * of a fix.
 */
type PixelBuffer = Uint32Array<ArrayBuffer>;

/** A decoded picture: 8-bit RGB triples, row-major. */
export interface WebpRaster {
  width: number;
  height: number;
  /** RGB, three bytes per pixel. Alpha is composited away by the caller. */
  pixels: Uint8Array;
  /** ARGB, one word per pixel, in case the caller wants the alpha. */
  argb: Uint32Array;
}

/**
 * A bit reader in VP8L's order: least-significant bit first, within bytes read
 * in increasing address order.
 *
 * `ok` goes false the first time a read runs past the end and never goes back.
 * Every loop in this file checks it, so a truncated file terminates instead of
 * decoding zeroes for ever.
 */
export class LosslessBitReader {
  private bitPosition = 0;
  ok = true;

  constructor(private readonly bytes: Uint8Array, private readonly start = 0,
    private readonly end = bytes.length) {}

  read(count: number): number {
    let value = 0;
    for (let i = 0; i < count; i++) {
      const index = this.start + (this.bitPosition >> 3);
      if (index >= this.end) { this.ok = false; return value; }
      const bit = (this.bytes[index] >> (this.bitPosition & 7)) & 1;
      value |= bit << i;
      this.bitPosition += 1;
    }
    return value >>> 0;
  }
}

