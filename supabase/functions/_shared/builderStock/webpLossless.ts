const COLOUR_CACHE_MULTIPLIER = 0x1e35a7bd;

interface HuffmanGroup {
  green: HuffmanCode;
  red: HuffmanCode;
  blue: HuffmanCode;
  alpha: HuffmanCode;
  distance: HuffmanCode;
}

function readHuffmanGroups(reader: LosslessBitReader, count: number,
  cacheBits: number): HuffmanGroup[] | null {
  const greenAlphabet = 256 + 24 + (cacheBits ? 1 << cacheBits : 0);
  const groups: HuffmanGroup[] = [];
  for (let i = 0; i < count; i++) {
    const green = readHuffmanCode(reader, greenAlphabet);
    const red = readHuffmanCode(reader, 256);
    const blue = readHuffmanCode(reader, 256);
    const alpha = readHuffmanCode(reader, 256);
    const distance = readHuffmanCode(reader, 40);
    if (!green || !red || !blue || !alpha || !distance) return null;
    groups.push({ green, red, blue, alpha, distance });
  }
  return groups;
}

interface StreamOptions {
  /** Only the top-level stream carries transforms and meta-Huffman. */
  topLevel: boolean;
  maxPixels: number;
}

/**
 * Decode one entropy-coded image, and the transforms wrapped around it.
 *
 * Recursive by design: the predictor map, the colour-transform map and the
 * palette are each an image in this same format, one level down, without
 * transforms of their own.
 */
function decodeImageStream(
  reader: LosslessBitReader, width: number, height: number, options: StreamOptions,
): { pixels: PixelBuffer; width: number; height: number } | null {
  if (width <= 0 || height <= 0) return null;
  if (width * height > options.maxPixels) return null;

  const transforms: Transform[] = [];
  let streamWidth = width;

  if (options.topLevel) {
    const seen = new Set<number>();
    while (reader.read(1)) {
      if (!reader.ok) return null;
      const type = reader.read(2);
      // Each transform may appear once. Without this a crafted file can
      // declare thousands and exhaust the budget before a pixel is read.
      if (seen.has(type)) return null;
      seen.add(type);

      if (type === PREDICTOR_TRANSFORM || type === COLOR_TRANSFORM) {
        const bits = reader.read(3) + 2;
        const tileWidth = (streamWidth + (1 << bits) - 1) >> bits;
        const tileHeight = (height + (1 << bits) - 1) >> bits;
        const sub = decodeImageStream(reader, tileWidth, tileHeight,
          { topLevel: false, maxPixels: options.maxPixels });
        if (!sub) return null;
        transforms.push({
          type, bits, width: tileWidth, height: tileHeight, data: sub.pixels,
        });
      } else if (type === SUBTRACT_GREEN) {
        transforms.push({ type, bits: 0, width: 0, height: 0, data: new Uint32Array(0) });
      } else if (type === COLOR_INDEXING_TRANSFORM) {
        const paletteSize = reader.read(8) + 1;
        const sub = decodeImageStream(reader, paletteSize, 1,
          { topLevel: false, maxPixels: options.maxPixels });
        if (!sub) return null;
        // The palette is stored as deltas along its own row.
        for (let i = 1; i < paletteSize; i++) {
          const previous = sub.pixels[i - 1];
          const value = sub.pixels[i];
          sub.pixels[i] = (
            ((((value >>> 24) + (previous >>> 24)) & 0xff) << 24)
            | (((((value >> 16) & 0xff) + ((previous >> 16) & 0xff)) & 0xff) << 16)
            | (((((value >> 8) & 0xff) + ((previous >> 8) & 0xff)) & 0xff) << 8)
            | (((value & 0xff) + (previous & 0xff)) & 0xff)
          ) >>> 0;
        }
        const bitsPerPixel = paletteSize <= 2 ? 1 : paletteSize <= 4 ? 2
          : paletteSize <= 16 ? 4 : 8;
        const perByte = 8 / bitsPerPixel;
        transforms.push({
          type, bits: bitsPerPixel, width: paletteSize, height: 1, data: sub.pixels,
        });
        streamWidth = Math.ceil(streamWidth / perByte);
      } else {
        return null;
      }
      if (!reader.ok) return null;
    }
    if (!reader.ok) return null;
  }

  // ── colour cache ─────────────────────────────────────────────────────────
  let cacheBits = 0;
  if (reader.read(1)) {
    cacheBits = reader.read(4);
    if (cacheBits < 1 || cacheBits > 11) return null;
  }
  if (!reader.ok) return null;

  // ── meta-Huffman ─────────────────────────────────────────────────────────
  let groupCount = 1;
  let metaBits = 0;
  let metaWidth = 0;
  let metaImage: Uint32Array | null = null;
  if (options.topLevel && reader.read(1)) {
    metaBits = reader.read(3) + 2;
    const metaW = (streamWidth + (1 << metaBits) - 1) >> metaBits;
    const metaH = (height + (1 << metaBits) - 1) >> metaBits;
    const sub = decodeImageStream(reader, metaW, metaH,
      { topLevel: false, maxPixels: options.maxPixels });
    if (!sub) return null;
    metaWidth = metaW;
    metaImage = sub.pixels;
    let highest = 0;
    for (const value of metaImage) {
      const group = ((value >> 8) & 0xffff);
      if (group > highest) highest = group;
    }
    groupCount = highest + 1;
    if (groupCount > 1 << 16) return null;
  }
  if (!reader.ok) return null;

  const groups = readHuffmanGroups(reader, groupCount, cacheBits);
  if (!groups) return null;

  // ── pixels ───────────────────────────────────────────────────────────────
  const count = streamWidth * height;
  const pixels = new Uint32Array(count);
  const cache = cacheBits ? new Uint32Array(1 << cacheBits) : null;
  const cacheShift = 32 - cacheBits;

  let position = 0;
  let x = 0;
  let y = 0;
  while (position < count) {
    if (!reader.ok) return null;
    const group = metaImage
      ? groups[((metaImage[(y >> metaBits) * metaWidth + (x >> metaBits)] >> 8) & 0xffff)]
      : groups[0];
    if (!group) return null;

    const symbol = readSymbol(reader, group.green);
    if (symbol < 0) return null;

    if (symbol < 256) {
      const red = readSymbol(reader, group.red);
      const blue = readSymbol(reader, group.blue);
      const alpha = readSymbol(reader, group.alpha);
      if (red < 0 || blue < 0 || alpha < 0) return null;
      const value = ((alpha << 24) | (red << 16) | (symbol << 8) | blue) >>> 0;
      pixels[position] = value;
      if (cache) cache[Math.imul(COLOUR_CACHE_MULTIPLIER, value) >>> cacheShift] = value;
      position += 1;
      if (++x === streamWidth) { x = 0; y += 1; }
      continue;
    }

    if (symbol < 256 + 24) {
      const length = prefixValue(reader, symbol - 256);
      const distanceSymbol = readSymbol(reader, group.distance);
      if (distanceSymbol < 0) return null;
      const planeCode = prefixValue(reader, distanceSymbol);
      const distance = planeToDistance(streamWidth, planeCode);
      if (distance > position || position + length > count) return null;
      for (let i = 0; i < length; i++) {
        const value = pixels[position - distance];
        pixels[position] = value;
        if (cache) cache[Math.imul(COLOUR_CACHE_MULTIPLIER, value) >>> cacheShift] = value;
        position += 1;
        if (++x === streamWidth) { x = 0; y += 1; }
      }
      continue;
    }

    if (!cache) return null;
    const entry = symbol - 256 - 24;
    if (entry >= cache.length) return null;
    const value = cache[entry];
    pixels[position] = value;
    position += 1;
    if (++x === streamWidth) { x = 0; y += 1; }
  }

  // ── unwind the transforms, last declared first ───────────────────────────
  let out = pixels;
  let outWidth = streamWidth;
  for (let i = transforms.length - 1; i >= 0; i--) {
    const transform = transforms[i];
    if (transform.type === PREDICTOR_TRANSFORM) {
      applyPredictor(out, outWidth, height, transform);
    } else if (transform.type === COLOR_TRANSFORM) {
      applyColourTransform(out, outWidth, height, transform);
    } else if (transform.type === SUBTRACT_GREEN) {
      applySubtractGreen(out);
    } else {
      const expanded = applyColourIndexing(out, outWidth, width, height, transform);
      if (!expanded) return null;
      out = expanded;
      outWidth = width;
    }
  }

  return { pixels: out, width: outWidth, height };
}

/**
 * Decode a VP8L chunk body (everything after the four-character code and its
 * length) into ARGB.
 */
export function decodeVp8l(
  body: Uint8Array, limits: { maxPixels: number },
): WebpRaster | null {
  if (body.length < 5 || body[0] !== 0x2f) return null;
  const reader = new LosslessBitReader(body, 1);
  const width = reader.read(14) + 1;
  const height = reader.read(14) + 1;
  reader.read(1); // alpha_is_used — the caller composites, so it is not needed
  const version = reader.read(3);
  if (!reader.ok || version !== 0) return null;
  if (width * height > limits.maxPixels) return null;

  const decoded = decodeImageStream(reader, width, height,
    { topLevel: true, maxPixels: limits.maxPixels });
  if (!decoded) return null;

  return { width, height, pixels: argbToRgb(decoded.pixels, width * height), argb: decoded.pixels };
}

/**
 * Flatten ARGB onto white.
 *
 * White rather than black because a transparent WebP is almost always a logo
 * or a cut-out on a light page, and compositing it onto black would invent a
 * huge flat dark region for the overlay detector to find.
 */
export function argbToRgb(argb: Uint32Array, count: number): Uint8Array {
  const out = new Uint8Array(count * 3);
  for (let i = 0; i < count; i++) {
    const value = argb[i];
    const alpha = value >>> 24;
    const red = (value >> 16) & 0xff;
    const green = (value >> 8) & 0xff;
    const blue = value & 0xff;
    if (alpha === 255) {
      out[i * 3] = red;
      out[i * 3 + 1] = green;
      out[i * 3 + 2] = blue;
    } else {
      const inverse = 255 - alpha;
      out[i * 3] = (red * alpha + 255 * inverse) / 255;
      out[i * 3 + 1] = (green * alpha + 255 * inverse) / 255;
      out[i * 3 + 2] = (blue * alpha + 255 * inverse) / 255;
    }
  }
  return out;
}
