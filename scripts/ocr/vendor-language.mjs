/**
 * Generate the OCR language module from the published npm package.
 *
 * GENERATED, NEVER HAND-EDITED — the same rule `canonicalRegistry.generated.ts`
 * and the template catalogue answer to. Run:
 *
 *     npm run ocr:vendor-language
 *
 * It writes `supabase/functions/_shared/builderStock/ocr/english.generated.ts`
 * from `@tesseract.js-data/eng`, which is where `tesseract.js` itself gets the
 * model — so what ships is the published artefact and not something this
 * repository produced.
 */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const PACKAGE = '@tesseract.js-data/eng@1.0.0';
// The integerised "best" model: 2.95 MB against 10.9 MB for the float one, at
// accuracy this product does not need to tell apart — a builder's brochure is
// set in ordinary type at ordinary sizes.
const MEMBER = 'package/4.0.0_best_int/eng.traineddata.gz';
const OUT = 'supabase/functions/_shared/builderStock/ocr/english.generated.ts';

const work = mkdtempSync(join(tmpdir(), 'ocr-lang-'));
try {
  const tgz = execFileSync('npm', ['pack', PACKAGE, '--silent'], { cwd: work })
    .toString().trim().split('\n').pop();
  execFileSync('tar', ['xzf', tgz, MEMBER], { cwd: work });
  const bytes = readFileSync(join(work, MEMBER));
  const sha = createHash('sha256').update(bytes).digest('hex');
  const b64 = bytes.toString('base64');
  writeFileSync(OUT, `/**
 * GENERATED BY \`npm run ocr:vendor-language\`. DO NOT EDIT.
 *
 * ${PACKAGE} :: ${MEMBER}
 * ${bytes.length} bytes, sha256 ${sha}
 *
 * Why this is a TypeScript module rather than a file on disk, and why it is
 * not fetched from a CDN at runtime: see \`languageData.ts\`.
 */
export const ENGLISH_TRAINEDDATA_SHA256 = '${sha}';
export const ENGLISH_TRAINEDDATA_BYTES = ${bytes.length};
export const ENGLISH_TRAINEDDATA_GZ_BASE64 =
  '${b64}';
`);
  console.log(`wrote ${OUT}: ${bytes.length} bytes, sha256 ${sha}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
